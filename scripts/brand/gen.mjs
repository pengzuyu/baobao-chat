#!/usr/bin/env node
// =============================================================================
// gen.mjs —— 品牌白标生成器（D31）
//
// 读 brand/brand.json（唯一品牌配置源）生成/更新五类产物：
//   client/src/shared/brand.ts        前端品牌常量（APP_NAME/TAGLINE/MAIL_DOMAIN/…，触点收敛唯一出口）
//   client/src-tauri/src/brand.rs     壳侧常量（APP_NAME/SCHEME，深链 register 消硬编码）
//   agent/crates/bbrt-session/src/    Agent 身份定制（AGENT_NAME/AGENT_IDENTITY，
//     brand.rs                          提示词开头句自称 + 企业身份段，D31 同源）
//   client/src-tauri/tauri.conf.json  原地 patch：productName/identifier/窗口标题/
//                                     deep-link schemes/updater pubkey
//   client/public/logo.svg            ← brand/assets/logo.svg 复制（favicon 同源）
//   client/index.html                 <title> 重写（page_title）
//
// 图标全套（src-tauri/icons/）不在本脚本：make brand 全量时经 tauri icon 重生成
// （输出可能非字节等价，上游只在换 icon.png 时跑，防日常 churn）。
//
// 用法：
//   node scripts/brand/gen.mjs           生成/更新产物（幂等：默认值跑两遍零 diff）
//   node scripts/brand/gen.mjs --check   只校验不写：产物与 brand.json 不一致 exit 1
//                                       （挂 build-desktop 前置，防改了 brand 忘跑生成器）
//
// identity 覆盖警告（D31 拍板：品牌可变、身份不变）：identifier/deep_link_scheme
// 偏离默认值时红字提示后果——改 identifier=appData 目录迁移全员静默登出；
// 改 scheme=服务端 BBC_DEEP_LINK_SCHEME 必须同步（oidc/web.go 深链 4 处同源）。
// =============================================================================

import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// 必须用 fileURLToPath 而非 URL.pathname：Windows 上 pathname 形如 /D:/a/...，
// resolve 会拼成 D:\D:\a\...（Windows 出包时品牌 --check 门禁首个 ENOENT 的根因）
const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const CHECK = process.argv.includes('--check');

// ── 读取与校验 brand.json ──
const BRAND_PATH = resolve(ROOT, 'brand/brand.json');
const brand = JSON.parse(readFileSync(BRAND_PATH, 'utf8'));

const REQUIRED = ['name', 'page_title', 'tagline', 'copyright', 'device_name'];
for (const k of REQUIRED) {
  if (typeof brand[k] !== 'string' || !brand[k].trim()) {
    console.error(`[brand] brand.json 缺字段或为空: ${k}`); process.exit(1);
  }
}
const identity = brand.identity ?? {};
for (const k of ['identifier', 'deep_link_scheme']) {
  if (typeof identity[k] !== 'string' || !identity[k].trim()) {
    console.error(`[brand] brand.json identity 缺字段: ${k}`); process.exit(1);
  }
}
if (typeof brand.updater_pubkey !== 'string') {
  console.error('[brand] brand.json 缺字段: updater_pubkey（未启用自更新填 ""）'); process.exit(1);
}
// 邮箱统一后缀（2026-11-18）：裸域名（不带 @/空格）；前端表单默认值 + 服务端 BBC_MAIL_DOMAIN 同源
if (typeof brand.mail_domain !== 'string' || !/^[^\s@]+$/.test(brand.mail_domain)) {
  console.error('[brand] brand.json mail_domain 缺失或非法（应为裸域名，如 bbc.io）'); process.exit(1);
}
// Agent 身份定制（2026-11-23）：agent.name 空=回退品牌 name（零配置跟品牌走）；
// agent.identity=企业自定义身份段（空=不追加），只进提示词不进 UI（前端展示面仍走品牌 name）
const agentCfg = brand.agent ?? {};
for (const k of ['name', 'identity']) {
  if (typeof agentCfg[k] !== 'string') {
    console.error(`[brand] brand.json agent.${k} 缺失或非字符串（可选自定义，至少填 ""）`); process.exit(1);
  }
}
const agentName = agentCfg.name.trim() || brand.name;

// ── identity 偏离默认值警告（D31 §3.2 高级覆盖区）──
const DEFAULT_IDENTITY = { identifier: 'com.baobaochat.client', deep_link_scheme: 'bbc' };
for (const [k, def] of Object.entries(DEFAULT_IDENTITY)) {
  if (identity[k] !== def) {
    console.warn(`\x1b[31m[brand] ⚠ identity.${k}="${identity[k]}" 偏离默认值 "${def}"：`);
    console.warn(k === 'identifier'
      ? '  identifier 变更 = appData/钥匙串目录迁移，老用户全员静默登出+本地数据不可见（D30 批2 更名史先例）\x1b[0m'
      : '  scheme 变更 = 服务端 BBC_DEEP_LINK_SCHEME 必须同步改，否则 OIDC 深链确认登录静默失效\x1b[0m');
  }
}

// ── mail_domain 偏离默认值警告（2026-11-18 邮箱统一后缀；定死型配置——改后不回收）──
if (brand.mail_domain !== 'bbc.io') {
  console.warn(`\x1b[31m[brand] ⚠ mail_domain="${brand.mail_domain}" 偏离默认值 "bbc.io"：`);
  console.warn('  服务端 BBC_MAIL_DOMAIN（deploy env / helm config.mailDomain）必须同步改（初始管理员邮箱与 mail 模块懒开户同源）；\x1b[0m');
  console.warn('  已建用户邮箱地址不变——历史地址与新后缀并存，切换前请确认存量影响\x1b[0m');
}

// ── 产物 1：前端 brand.ts ──
const brandTs = `// AUTO-GENERATED by scripts/brand/gen.mjs（D31）—— 勿手改；改 brand/brand.json 后跑 make brand-conf
// 全前端品牌文案唯一出口（登录页/关于/通知署名/设备名等触点一律引这里）

export const APP_NAME = ${JSON.stringify(brand.name)};
export const PAGE_TITLE = ${JSON.stringify(brand.page_title)};
export const TAGLINE = ${JSON.stringify(brand.tagline)};
export const COPYRIGHT = ${JSON.stringify(brand.copyright)};
export const DEVICE_NAME = ${JSON.stringify(brand.device_name)};
export const MAIL_DOMAIN = ${JSON.stringify(brand.mail_domain)};
`;

// ── 产物 2：壳 brand.rs ──
const brandRs = `//! AUTO-GENERATED by scripts/brand/gen.mjs（D31）—— 勿手改；改 brand/brand.json 后跑 make brand-conf
//! 壳侧品牌与身份常量；SCHEME 与 tauri.conf.json plugins.deep-link 同源生成（勿在代码里散写）

/// 产品显示名
pub const APP_NAME: &str = ${JSON.stringify(brand.name)};
/// 深链 scheme（\`${identity.deep_link_scheme}://auth\`，D28 OIDC 确认登录）
pub const SCHEME: &str = ${JSON.stringify(identity.deep_link_scheme)};
`;

// ── 产物 3：agent 身份定制 brand.rs（bbrt-session）──
// AGENT_NAME：提示词开头句「你是 X 的本机 Agent」自称（name 空值在此回退品牌 name）
// AGENT_IDENTITY：企业身份段（空=不追加），拼在公共 SYSTEM_PROMPT 之后、场景段之前
const agentBrandRs = `//! AUTO-GENERATED by scripts/brand/gen.mjs（D31）—— 勿手改；改 brand/brand.json 后跑 make brand-conf
//! Agent 身份定制（企业白标）：只影响模型提示词自称与身份段，UI 展示面仍走品牌 name

/// Agent 自称（提示词开头句「你是 X 的本机 Agent，服务单一用户」）
pub const AGENT_NAME: &str = ${JSON.stringify(agentName)};
/// 企业自定义身份段（空=不追加）；拼在公共 SYSTEM_PROMPT 之后、场景段之前
pub const AGENT_IDENTITY: &str = ${JSON.stringify(agentCfg.identity)};
`;

// ── 产物 4：tauri.conf.json 原地 patch ──
const TAURI_CONF = resolve(ROOT, 'client/src-tauri/tauri.conf.json');
const tauriNow = JSON.parse(readFileSync(TAURI_CONF, 'utf8'));
const tauriWant = structuredClone(tauriNow);
tauriWant.productName = brand.name;
tauriWant.identifier = identity.identifier;
tauriWant.app.windows[0].title = brand.name;
tauriWant.plugins['deep-link'].desktop.schemes = [identity.deep_link_scheme];
tauriWant.plugins.updater.pubkey = brand.updater_pubkey;
let tauriWantText = JSON.stringify(tauriWant, null, 2) + '\n';
// 保持 schemes 单行风格（原文件手写紧凑格式，避免纯格式 diff）
tauriWantText = tauriWantText.replace(/("schemes": \[)[\s\S]*?(\])/, (_m, a, z) => {
  const items = tauriWant.plugins['deep-link'].desktop.schemes.map((s) => JSON.stringify(s)).join(', ');
  return `${a}${items}${z}`;
});

// ── 产物 5：logo.svg 复制（内容比对，幂等）──
const LOGO_SRC = resolve(ROOT, 'brand/assets/logo.svg');
const LOGO_DST = resolve(ROOT, 'client/public/logo.svg');
const logoSrc = readFileSync(LOGO_SRC, 'utf8');
let logoSame = true;
try { logoSame = readFileSync(LOGO_DST, 'utf8') === logoSrc; } catch { logoSame = false; }

// ── 产物 6：index.html <title> 重写（正则幂等）──
const INDEX_HTML = resolve(ROOT, 'client/index.html');
const htmlNow = readFileSync(INDEX_HTML, 'utf8');
const titleRe = /<title>[^<]*<\/title>/;
if (!titleRe.test(htmlNow)) {
  console.error('[brand] client/index.html 未找到 <title> 标签'); process.exit(1);
}
const htmlWant = htmlNow.replace(titleRe, `<title>${brand.page_title}</title>`);

// ── 落盘 / 校验 ──
const outputs = [
  { path: 'client/src/shared/brand.ts', text: brandTs },
  { path: 'client/src-tauri/src/brand.rs', text: brandRs },
  { path: 'agent/crates/bbrt-session/src/brand.rs', text: agentBrandRs },
  { path: 'client/src-tauri/tauri.conf.json', text: tauriWantText },
  { path: 'client/index.html', text: htmlWant },
];

let fail = 0;
for (const out of outputs) {
  const abs = resolve(ROOT, out.path);
  let cur = null;
  try { cur = readFileSync(abs, 'utf8'); } catch { /* 不存在 */ }
  if (cur === out.text) continue; // 幂等：内容一致跳过
  if (CHECK) {
    console.error(`[brand] ✗ --check 不一致: ${out.path}（改了 brand/brand.json 后先跑 make brand-conf）`);
    fail++;
  } else {
    writeFileSync(abs, out.text);
    console.log(`[brand] ✔ 已生成: ${out.path}`);
  }
}
if (!logoSame) {
  if (CHECK) {
    console.error('[brand] ✗ --check 不一致: client/public/logo.svg ≠ brand/assets/logo.svg');
    fail++;
  } else {
    copyFileSync(LOGO_SRC, LOGO_DST);
    console.log('[brand] ✔ 已复制: client/public/logo.svg');
  }
}

if (CHECK) {
  if (fail) { console.error(`[brand] --check 失败（${fail} 处产物过期）`); process.exit(1); }
  console.log('[brand] --check 通过：品牌产物与 brand/brand.json 一致');
} else {
  console.log('[brand] 完成（图标全套不在本脚本：换 icon.png 后跑 make brand）');
}
